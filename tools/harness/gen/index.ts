import fs from 'node:fs';
import path from 'node:path';
import { budget } from '../core/config.ts';
import { isValidDate } from '../core/frontmatter.ts';
import { matchAny } from '../core/glob.ts';
import type { Config, Doc, Scan } from '../core/types.ts';

export const GENERATED_MARK = '<!-- GENERATED by tools/harness — do not edit -->';

interface Entry {
  link: string;
  title: string;
  summary: string;
  keywords: string[];
  updated?: string;
}

interface Node {
  summary: string;
  keywords: string[];
  updated: string;
  files: Entry[];
  subs: Entry[];
}

const str = (v: unknown): string => (typeof v === 'string' ? v : '');

/** The directory whose INDEX.md lists this doc (skills belong to the parent of their folder). */
export function ownerDir(doc: Doc): string {
  if (doc.kind !== 'skill' && doc.kind !== 'agent') return doc.dir;
  const i = doc.dir.lastIndexOf('/');
  return i < 0 ? '' : doc.dir.slice(0, i);
}

function metaKeywords(doc: Doc): string[] {
  const meta = doc.data?.metadata;
  const kw =
    meta && typeof meta === 'object' ? (meta as Record<string, unknown>).keywords : undefined;
  if (Array.isArray(kw)) return kw.map(String);
  return typeof kw === 'string'
    ? kw
        .split(',')
        .map((k) => k.trim())
        .filter(Boolean)
    : [];
}

function claudeEntry(doc: Doc, config: Config, link: string, name: string): Entry {
  const s = config.index.claudeMdSummary;
  return { link, title: name, summary: doc.dir === '' ? s.root : s.other, keywords: [] };
}

function specialEntry(doc: Doc, config: Config, link: string, name: string): Entry {
  const def = config.frontmatter.special.find((d) => d.kind === doc.kind)!;
  const fallback = doc.kind === 'skill' ? doc.dir.slice(doc.dir.lastIndexOf('/') + 1) : name;
  const title = str(doc.data?.[def.titleField ?? 'name']) || fallback;
  return {
    link,
    title,
    summary: str(doc.data?.[def.summaryField ?? 'description']),
    keywords: metaKeywords(doc),
  };
}

function docEntry(doc: Doc, config: Config, owner: string): Entry {
  const link = owner ? doc.rel.slice(owner.length + 1) : doc.rel;
  const name = doc.rel.slice(doc.rel.lastIndexOf('/') + 1);
  if (doc.kind === 'claude') return claudeEntry(doc, config, link, name);
  if (doc.kind === 'skill' || doc.kind === 'agent') return specialEntry(doc, config, link, name);
  const kw = Array.isArray(doc.data?.keywords)
    ? doc.data.keywords.filter((k) => typeof k === 'string')
    : [];
  const updated = str(doc.data?.updated);
  return {
    link,
    title: str(doc.data?.title) || name,
    summary: str(doc.data?.summary),
    keywords: kw as string[],
    updated: isValidDate(updated) ? updated : undefined,
  };
}

function topKeywords(entries: Entry[], max: number): string[] {
  const counts = new Map<string, number>();
  for (const e of entries) for (const k of e.keywords) counts.set(k, (counts.get(k) ?? 0) + 1);
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
    .slice(0, max)
    .map(([k]) => k);
}

function buildNode(dir: string, docs: Doc[], subs: Entry[], config: Config): Node | null {
  if (docs.length === 0 && subs.length === 0) return null;
  const files = docs
    .map((d) => docEntry(d, config, dir))
    .sort((a, b) => (a.link < b.link ? -1 : 1));
  const all = [...files, ...subs];
  const dates = all.map((e) => e.updated).filter((d): d is string => !!d);
  const updated = dates.length
    ? dates.reduce((a, b) => (a > b ? a : b))
    : config.index.fallbackDate;
  const label = dir || 'root';
  return {
    summary: `Index of ${label}: ${files.length} files, ${subs.length} subdirectories`,
    keywords: topKeywords(all, budget(config, 'fm_keywords_max').value),
    updated,
    files,
    subs,
  };
}

const cell = (s: string): string => s.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();

function table(head: string[], rows: string[][]): string[] {
  const out = [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`];
  for (const r of rows) out.push(`| ${r.map(cell).join(' | ')} |`);
  return out;
}

export function renderNode(dir: string, n: Node): string {
  const title = `Index: ${dir || 'root'}`;
  const lines = [
    '---',
    `title: ${JSON.stringify(title)}`,
    `summary: ${JSON.stringify(n.summary)}`,
    `keywords: [${n.keywords.map((k) => JSON.stringify(k)).join(', ')}]`,
    'type: index',
    'status: active',
    `updated: ${n.updated}`,
    'generated: true',
    '---',
    GENERATED_MARK,
    '',
    `# ${title}`,
    '',
  ];
  if (n.subs.length) {
    lines.push('## Subdirectories', '');
    lines.push(
      ...table(
        ['Directory', 'Summary', 'Keywords'],
        n.subs.map((e) => [`[${e.title}](${e.link})`, e.summary, e.keywords.join(', ')]),
      ),
    );
    lines.push('');
  }
  if (n.files.length) {
    lines.push('## Files', '');
    lines.push(
      ...table(
        ['File', 'Title', 'Summary', 'Keywords'],
        n.files.map((e) => [`[${e.link}](${e.link})`, e.title, e.summary, e.keywords.join(', ')]),
      ),
    );
    lines.push('');
  }
  return lines.join('\n');
}

const depthOf = (d: string): number => (d === '' ? 0 : d.split('/').length);

/** Map of INDEX.md repo-relative path to its expected content. */
function docsByDir(scan: Scan): Map<string, Doc[]> {
  const byDir = new Map<string, Doc[]>();
  for (const d of scan.docs) {
    if (d.kind === 'index' || d.kind === 'exempt') continue;
    const o = ownerDir(d);
    byDir.set(o, [...(byDir.get(o) ?? []), d]);
  }
  return byDir;
}

function subEntries(scan: Scan, dir: string, nodes: Map<string, Node>): Entry[] {
  const subs: Entry[] = [];
  for (const name of scan.dirs.get(dir)!.subdirs.slice().sort()) {
    const n = nodes.get(dir ? `${dir}/${name}` : name);
    if (n)
      subs.push({
        link: `${name}/INDEX.md`,
        title: `${name}/`,
        summary: n.summary,
        keywords: n.keywords,
        updated: n.updated,
      });
  }
  return subs;
}

export function generateIndexes(scan: Scan): Map<string, string> {
  const { config } = scan;
  const byDir = docsByDir(scan);
  const nodes = new Map<string, Node>();
  const dirs = [...scan.dirs.keys()].sort((a, b) => depthOf(b) - depthOf(a));
  for (const dir of dirs) {
    if (dir !== '' && matchAny(dir, config.index.skipDirs)) continue;
    const subs = subEntries(scan, dir, nodes);
    const node = buildNode(dir, byDir.get(dir) ?? [], subs, config);
    if (node) nodes.set(dir, node);
  }
  const out = new Map<string, string>();
  for (const dir of [...nodes.keys()].sort()) {
    out.set(dir ? `${dir}/INDEX.md` : 'INDEX.md', renderNode(dir, nodes.get(dir)!));
  }
  return out;
}

export function writeIfChanged(root: string, rel: string, content: string): boolean {
  const abs = path.join(root, rel);
  const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n') : null;
  if (current === content) return false;
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content, 'utf8');
  return true;
}

/** Writes changed indexes, removes orphaned INDEX.md files. Returns changed paths. */
export function writeIndexes(scan: Scan): string[] {
  const expected = generateIndexes(scan);
  const changed: string[] = [];
  for (const [rel, content] of expected)
    if (writeIfChanged(scan.root, rel, content)) changed.push(rel);
  for (const d of scan.docs) {
    if (d.kind === 'index' && !expected.has(d.rel)) {
      fs.rmSync(path.join(scan.root, d.rel));
      changed.push(d.rel);
    }
  }
  return changed;
}
